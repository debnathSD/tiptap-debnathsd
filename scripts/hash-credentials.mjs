#!/usr/bin/env node
/**
 * Generate the sign-in verifier in src/auth/credentials.ts.
 *
 *   AUTH_USER=… AUTH_PASSWORD=… node scripts/hash-credentials.mjs            # replace all accounts
 *   AUTH_USER=… AUTH_PASSWORD=… node scripts/hash-credentials.mjs --append   # add an account
 *
 * Each account is a random salt and a PBKDF2-SHA256 digest of "user:password";
 * the user ID and password themselves are never written. Must match src/auth/verify.ts.
 */
import { pbkdf2Sync, randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ITERATIONS = 600_000
const user = process.env.AUTH_USER?.trim()
const password = process.env.AUTH_PASSWORD
const append = process.argv.includes('--append')

if (!user || !password) {
  console.error('Set AUTH_USER and AUTH_PASSWORD in the environment.')
  process.exit(1)
}

const out = fileURLToPath(new URL('../src/auth/credentials.ts', import.meta.url))
const accounts = []
if (append && existsSync(out)) {
  for (const [, salt, hash] of readFileSync(out, 'utf8').matchAll(/\{ salt: '([^']+)', hash: '([^']+)' \}/g)) accounts.push({ salt, hash })
}

const salt = randomBytes(16)
const hash = pbkdf2Sync(`${user}:${password}`, salt, ITERATIONS, 32, 'sha256')
accounts.push({ salt: salt.toString('base64'), hash: hash.toString('base64') })

writeFileSync(
  out,
  `// Generated by scripts/hash-credentials.mjs — salted PBKDF2 digests, not credentials.
export const CREDENTIALS = {
  iterations: ${ITERATIONS},
  accounts: [
${accounts.map(a => `    { salt: '${a.salt}', hash: '${a.hash}' },`).join('\n')}
  ],
}
`,
)
console.log(`Wrote ${out} (${accounts.length} account${accounts.length === 1 ? '' : 's'})`)
