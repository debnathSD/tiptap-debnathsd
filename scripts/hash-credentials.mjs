#!/usr/bin/env node
/**
 * Generate the login verifier in src/auth/credentials.ts.
 *
 *   AUTH_USER=… AUTH_PASSWORD=… node scripts/hash-credentials.mjs
 *
 * Only a random salt and a PBKDF2-SHA256 digest of "user:password" are
 * written — never the credentials themselves. Must match src/auth/verify.ts.
 */
import { pbkdf2Sync, randomBytes } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ITERATIONS = 600_000
const user = process.env.AUTH_USER?.trim()
const password = process.env.AUTH_PASSWORD

if (!user || !password) {
  console.error('Set AUTH_USER and AUTH_PASSWORD in the environment.')
  process.exit(1)
}

const salt = randomBytes(16)
const hash = pbkdf2Sync(`${user}:${password}`, salt, ITERATIONS, 32, 'sha256')

const out = fileURLToPath(new URL('../src/auth/credentials.ts', import.meta.url))
writeFileSync(
  out,
  `// Generated by scripts/hash-credentials.mjs — a salted PBKDF2 digest, not the credentials.
export const CREDENTIALS = {
  salt: '${salt.toString('base64')}',
  iterations: ${ITERATIONS},
  hash: '${hash.toString('base64')}',
}
`,
)
console.log(`Wrote ${out}`)
