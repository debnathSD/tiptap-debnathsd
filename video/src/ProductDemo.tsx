import { AbsoluteFill, Audio, Sequence, staticFile } from 'remotion'
import { BlocksIntro } from './scenes/BlocksIntro'
import { Devices, Outro } from './scenes/Closing'
import { FeatureStep } from './scenes/FeatureStep'
import { PageReveal } from './scenes/PageReveal'
import { STEPS } from './steps'
import { backdrop } from './theme'
import { SCENES, type SceneKey } from './timeline'

export { DEMO_FRAMES } from './timeline'

function render(key: SceneKey, step?: number) {
  if (key === 'intro') return <BlocksIntro />
  if (key === 'reveal') return <PageReveal />
  if (key === 'devices') return <Devices />
  if (key === 'outro') return <Outro />
  return <FeatureStep step={STEPS[step!]} index={step!} total={STEPS.length} />
}

export function ProductDemo() {
  return (
    <AbsoluteFill style={{ background: backdrop }}>
      {/* Original score + sound design, generated by scripts/soundtrack.mjs from the same timeline. */}
      <Audio src={staticFile('audio/soundtrack.m4a')} />
      {SCENES.map(scene => (
        <Sequence key={scene.key} from={scene.from} durationInFrames={scene.frames} name={scene.key}>
          {render(scene.key, scene.step)}
        </Sequence>
      ))}
    </AbsoluteFill>
  )
}
